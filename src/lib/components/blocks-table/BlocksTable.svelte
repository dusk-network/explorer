<svelte:options immutable={true} />

<script>
  import { mdiCubeOutline } from "@mdi/js";

  import { Icon, RelativeTime } from "$lib/dusk/components";
  import { AppAnchor, TransactionParty } from "$lib/components";
  import {
    Table,
    TableBody,
    TableCell,
    TableHead,
    TableRow,
  } from "$lib/components/table";
  import { formatDusk, formatDuskExact, formatFee } from "$lib/dusk/currency";
  import { formatDateTime } from "$lib/dusk/date";
  import { makeClassName } from "$lib/dusk/string";
  import { createValueFormatter } from "$lib/dusk/value";

  import "./BlocksTable.css";

  /** @type {string | undefined} */
  export let className = undefined;

  /** @type {Block[]} */
  export let data;

  /**
   * Whether the list is the home page's short one. The blocks page also
   * says, for a block with transactions, how full it was and the fees it
   * took.
   */
  export let brief = false;

  const numberFormatter = createValueFormatter("en");

  /**
   * The share of a block's gas limit its transactions used, as a percent.
   *
   * @param {number} used
   * @param {number} limit
   */
  function fullness(used, limit) {
    const share = limit ? (used / limit) * 100 : 0;

    return share < 0.01
      ? "<0.01%"
      : `${share.toFixed(2).replace(/\.?0+$/, "")}%`;
  }

  $: classes = makeClassName([
    "blocks-table",
    brief ? "blocks-table--brief" : "blocks-table--full",
    className,
  ]);
</script>

<Table className={classes}>
  <TableHead>
    <TableRow>
      <TableCell type="th">Block</TableCell>
      <TableCell type="th">Generated by</TableCell>
      <TableCell align="right" type="th">Transactions</TableCell>
      <TableCell align="right" type="th">Reward</TableCell>
    </TableRow>
  </TableHead>
  <TableBody>
    {#each data as block (block)}
      {@const count = block.transactions.data.length}
      {@const { gasLimit, gasUsed } = block.transactions.stats}
      <TableRow>
        <TableCell>
          <div class="block__main">
            <span aria-hidden="true" class="row-icon"
              ><Icon path={mdiCubeOutline} /></span
            >
            <div class="block__who">
              <AppAnchor
                className="block__link chain-link"
                href={`/blocks/block?id=${block.header.hash}`}
                >{numberFormatter(block.header.height)}</AppAnchor
              >
              <span class="row-line">
                <RelativeTime
                  autoRefresh
                  className="block__time"
                  data-tooltip-id="main-tooltip"
                  data-tooltip-text={formatDateTime(block.header.date)}
                  date={block.header.date}
                />
              </span>
            </div>
          </div>
        </TableCell>
        <TableCell>
          {#if block.header.generator}
            <TransactionParty
              narrow={brief}
              party={{ address: block.header.generator, kind: "account" }}
            />
          {:else}
            <span class="block__none">—</span>
          {/if}
        </TableCell>
        <TableCell align="right">
          <span class:block__none={!brief && count === 0}
            >{numberFormatter(count)}</span
          >
          {#if !brief && gasUsed > 0}
            <span
              class="row-line block__line"
              title="{numberFormatter(gasUsed)} of {numberFormatter(
                gasLimit
              )} gas">{fullness(gasUsed, gasLimit)} full</span
            >
          {/if}
        </TableCell>
        <TableCell align="right"
          ><span class="row-amount"
            ><span title="{formatDuskExact(block.header.reward)} DUSK"
              >{formatDusk(block.header.reward)}</span
            >
            <span class="row-unit">DUSK</span></span
          >
          {#if !brief && block.header.feespaid > 0}
            <span
              class="row-line block__line"
              title="{formatDuskExact(block.header.feespaid)} DUSK"
              >+ {formatFee(block.header.feespaid)} DUSK fees</span
            >
          {/if}
        </TableCell>
      </TableRow>
    {/each}
  </TableBody>
</Table>
