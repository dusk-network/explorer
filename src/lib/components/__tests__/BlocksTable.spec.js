import { afterAll, afterEach, describe, expect, it, vi } from "vitest";
import { cleanup, render } from "@testing-library/svelte";
import { mapWith, slice } from "lamb";

import { gqlBlock, gqlBlocks } from "$lib/mock-data";
import { transformBlock } from "$lib/chain-info";
import { formatDusk } from "$lib/dusk/currency";
import { shortId } from "$lib/dusk/string";

import { BlocksTable } from "..";

describe("Blocks Table", () => {
  vi.useFakeTimers();
  vi.setSystemTime(new Date(2024, 4, 30));

  const transformBlocks = mapWith(transformBlock);
  const data = slice(transformBlocks(gqlBlocks.blocks), 0, 10);

  const baseProps = {
    data: data,
  };
  const baseOptions = {
    props: baseProps,
    target: document.body,
  };

  afterEach(cleanup);

  afterAll(() => {
    vi.useRealTimers();
  });

  /** @param {HTMLElement} container */
  const getHeaders = (container) =>
    Array.from(container.querySelectorAll("th"), (th) =>
      th.textContent?.trim()
    );

  it("should say who made each block on the blocks page, opening its account, and leave it out on the home page", async () => {
    const { container, rerender } = render(BlocksTable, baseOptions);

    expect(getHeaders(container)).toStrictEqual([
      "Block",
      "Generated by",
      "Transactions",
      "Reward",
    ]);

    const generators = Array.from(
      container.querySelectorAll("tbody tr"),
      (row) => row.querySelectorAll("td")[1].querySelector("a")
    );

    expect(generators).toHaveLength(data.length);
    generators.forEach((link, i) => {
      const key = data[i].header.generator;

      expect(link?.textContent?.trim()).toBe(shortId(key));
      expect(link).toHaveAttribute(
        "href",
        `/some-base-path/accounts/?key=${key}`
      );
    });

    await rerender({ ...baseProps, brief: true });

    // The home page's short list says who made each block too.
    expect(getHeaders(container)).toStrictEqual([
      "Block",
      "Generated by",
      "Transactions",
      "Reward",
    ]);
    expect(container.querySelectorAll("a[href*='/accounts/']")).toHaveLength(
      data.length
    );
  });

  it("should say how full a block with transactions was and the fees it took, and nothing more for an empty one", () => {
    // Two transactions, 580,718 gas of 5,000,000,000, and 580,718 LUX in fees.
    const busy = transformBlock(gqlBlock.block);
    const [empty] = data;
    const { container } = render(BlocksTable, {
      props: { data: [busy, empty] },
    });
    const [busyRow, emptyRow] = container.querySelectorAll("tbody tr");

    /** @param {Element} row */
    const numbersOf = (row) =>
      Array.from(row.querySelectorAll("td"), (td) =>
        td.textContent?.replace(/\s+/g, " ").trim()
      ).slice(2);

    expect(numbersOf(busyRow)).toStrictEqual([
      "2 0.01% full",
      "16 DUSK + 0.00058 DUSK fees",
    ]);
    expect(busyRow.querySelector(".block__line")).toHaveAttribute(
      "title",
      "580,718 of 5,000,000,000 gas"
    );
    expect(numbersOf(emptyRow)).toStrictEqual([
      "0",
      `${formatDusk(empty.header.reward)} DUSK`,
    ]);
  });
});
